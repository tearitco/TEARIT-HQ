#!/bin/sh
# gen_choices.sh - write choices.objects.pdl and choices.chtpm FROM data/sources.pdl (the one place the reader's menu order and labels live).
# Run after editing sources.pdl:  sh gen_choices.sh   (idempotent; prints the rows it wrote)
HERE="$(cd "$(dirname "$0")" && pwd)"; SRC="$HERE/data/sources.pdl"
[ -f "$SRC" ] || { echo "gen_choices: missing $SRC" >&2; exit 1; }
ROWS=$(awk -F' [|] ' '$1 == "SOURCE" && $2 ~ /^[0-9]+$/ {print $2 "\t" $3 "\t" $4}' "$SRC" | sort -n)
[ -n "$ROWS" ] || { echo "gen_choices: no SOURCE rows in $SRC" >&2; exit 1; }
# refuse an action that has no branch folder: a menu row that does nothing is the bug this file exists to avoid
BAD=$(printf '%s\n' "$ROWS" | while IFS="$(printf '\t')" read -r _o a _l; do [ -f "$HERE/branches/$a/run.sh" ] || echo "$a"; done)
[ -z "$BAD" ] || { echo "gen_choices: no branches/<action>/run.sh for: $BAD" >&2; exit 1; }
printf '%s\n' "$ROWS" | while IFS="$(printf '\t')" read -r _o a l; do printf 'OBJECT | label=%s | action=%s\n' "$l" "$a"; done > "$HERE/choices.objects.pdl.new"
{ printf '<!-- menu.chtpm - GENERATED by gen_choices.sh from data/sources.pdl; edit the data, not this file. -->\n<window class="entity-menu">\n  <page name="main">\n'
  printf '%s\n' "$ROWS" | while IFS="$(printf '\t')" read -r _o a l; do printf '    <item label="%s" action="%s"/>\n' "$l" "$a"; done
  printf '  </page>\n</window>\n'; } > "$HERE/choices.chtpm.new"
mv "$HERE/choices.objects.pdl.new" "$HERE/choices.objects.pdl"; mv "$HERE/choices.chtpm.new" "$HERE/choices.chtpm"
cat "$HERE/choices.objects.pdl"
