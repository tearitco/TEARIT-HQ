#!/usr/bin/env python3
"""cdda_tiles_to_pdl.py - one-shot converter (Slice A of CDDA-DF-SUBAGENT-BUILD-2026-10-12.md): UltimateCataclysm (loose PNGs + the per-sprite JSON files that sit beside them)
-> house pipe rows in shared/cdda-tiles.pdl. The GAME never reads JSON; after this it opens the .pdl only. Python is allowed for one-off converters (house rule); rerun to regenerate.
  TILE | id | png | w | h | ox | oy        one row per PNG (id = basename; png = path under the UltiCa tree; w,h from the pngs_<bucket>_<w>x<h> folder name;
                                            ox,oy from tile_info.json only for the tall bucket (oy -32) and the small bucket (ox 6), else 0 | 0)
  PART | id | role | sprite | n            the connection / variant table copied out of the sprite JSON: role = fg, bg, or the JSON's own additional_tiles ids
                                            (unconnected, center, corner, edge, t_connection, end_piece ...); weighted variants use role 'weight' with n = the weight;
                                            other lists keep their order in n (corner = nw ne se sw as in the JSON).
Usage: python3 cdda_tiles_to_pdl.py [<UltimateCataclysm dir>] [<out.pdl>]"""
import json, os, re, sys
ROOT = sys.argv[1] if len(sys.argv) > 1 else os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..', '..', '..', '#.NNEST_ASSETS', 'cdda-tilesets', 'gfx', 'UltimateCataclysm')
OUT = sys.argv[2] if len(sys.argv) > 2 else os.path.join(os.path.dirname(os.path.abspath(__file__)), 'cdda-tiles.pdl')
ROOT = os.path.normpath(ROOT)
BUCKET_PRIORITY = ['normal', 'tall', 'small', 'centered', 'large', 'huge', 'giant', 'human_body', 'human_body_plus', 'filler', 'fillergiant', 'fillerhoder', 'filler_tall', 'incomplete', 'incomplete_large']
def bucket_rank(b):
    return BUCKET_PRIORITY.index(b) if b in BUCKET_PRIORITY else len(BUCKET_PRIORITY)
tiles, parts = [], []
dirs = sorted(d for d in os.listdir(ROOT) if d.startswith('pngs_') and os.path.isdir(os.path.join(ROOT, d)))
for f in sorted(os.listdir(ROOT)):      # PNGs at the top of the tree (fallback.png): 32x32, no offset
    if f.endswith('.png'): tiles.append((f[:-4], f, 32, 32, 0, 0))
def parse_dir(d):
    m = re.match(r'pngs_(.+)_(\d+)x(\d+)$', d)
    return (m.group(1), int(m.group(2)), int(m.group(3))) if m else (d[5:], 32, 32)
for d in sorted(dirs, key=lambda x: (bucket_rank(parse_dir(x)[0]), x)):
    bucket, w, h = parse_dir(d)
    ox, oy = (0, 0)
    if bucket == 'tall': oy = -32
    elif bucket == 'small': ox = 6
    for dp, dn, fn in os.walk(os.path.join(ROOT, d)):
        dn.sort()
        for f in sorted(fn):
            p = os.path.join(dp, f)
            if f.endswith('.png'):
                tiles.append((f[:-4], os.path.relpath(p, ROOT).replace(os.sep, '/'), w, h, ox, oy))
            elif f.endswith('.json'):
                try: data = json.load(open(p, encoding='utf-8'))
                except Exception: continue
                for e in (data if isinstance(data, list) else [data]):
                    if not isinstance(e, dict) or 'id' not in e: continue
                    ids = e['id'] if isinstance(e['id'], list) else [e['id']]
                    def emit(role, val):
                        items = val if isinstance(val, list) else [val]
                        for n, it in enumerate(items):
                            if isinstance(it, dict):
                                spr = it.get('sprite'); wt = it.get('weight', 1)
                                if isinstance(spr, list): spr = spr[0] if spr else None
                                if spr: parts.append((i, 'weight', spr, wt))
                            elif isinstance(it, str) and it:
                                parts.append((i, role, it, n))
                    for i in ids:
                        if not isinstance(i, str): continue
                        for key in ('fg', 'bg'):
                            if key in e: emit(key, e[key])
                        for at in e.get('additional_tiles', []) or []:
                            if isinstance(at, dict) and isinstance(at.get('id'), str) and 'fg' in at: emit(at['id'], at['fg'])
with open(OUT, 'w', encoding='utf-8') as o:
    o.write('SECTION | KEY | VALUE\n' + '-' * 30 + '\n')
    o.write('# cdda-tiles.pdl - generated by shared/cdda_tiles_to_pdl.py from #.NNEST_ASSETS/cdda-tilesets/gfx/UltimateCataclysm (UltiCa, CC-BY-SA 3.0). Do not edit; rerun the converter.\n')
    o.write('# TILE | id | png | w | h | ox | oy      png is relative to the UltimateCataclysm folder; rows are ordered by bucket priority (normal first), so the FIRST row of an id is the one to draw.\n')
    o.write('# PART | id | role | sprite | n          role fg/bg = the sprite(s) the id draws; unconnected/center/corner/edge/t_connection/end_piece = multitile connection sprites (n = order in the JSON: corner nw ne se sw);\n')
    o.write('#                                        role weight = random variants, n = weight. A sprite is a TILE id.\n')
    for t in tiles: o.write('TILE | %s | %s | %d | %d | %d | %d\n' % t)
    for q in parts: o.write('PART | %s | %s | %s | %s\n' % q)
pngs = sum(1 for _ in (f for dp, dn, fn in os.walk(ROOT) for f in fn if f.endswith('.png')))
print('PNG files on disk: %d   TILE rows: %d   PART rows: %d   -> %s (%.1f MB)' % (pngs, len(tiles), len(parts), OUT, os.path.getsize(OUT) / 1048576))
