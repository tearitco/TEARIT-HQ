#!/bin/bash
# nb_spa_click_test.sh - G1.5: a click on a rendered row re-renders WITHOUT
# a reload.
#
# The plan calls this "already true today via EVENT; pin it in the suite so
# G1 cannot regress it". That is exactly right, and the reason to pin it is
# the same as the reason to pin any invisible contract: the tick loop and
# the push protocol (G1.1/G1.3) changed how the worker is driven, and the
# cheapest way for those to break click-through would be for the click path
# to start costing a reload - which looks fine on screen and is the whole
# difference between an app and a document.
#
# So this asserts two things, and the second is the KPI:
#   1. clicking a rendered row produces a NEW render whose rows changed;
#   2. the page's own state survived - proven by n, the page's click
#      counter, which a real reload resets to 0. The suite forces a real
#      reload to prove that reset is observable, so 'clicked 2' is a
#      measurement rather than a constant.
#
# Hermetic: worker RPC directly. No browser, no X display, no other agent's
# window. The DOM fixture is generated by tests/g1_make_dom.c, never hand
# written - see that file for why the attrs blob matters.
set -u
HERE="$(cd "$(dirname "$0")" && pwd)"
PKG="$(cd "$HERE/.." && pwd)"
WORKER="$PKG/ops/+x/nb_js_worker.+x"
FAIL=0
fail() { echo "FAIL: $*"; FAIL=1; }

[ -x "$WORKER" ] || { echo "FAIL: worker not built ($WORKER)"; exit 1; }

WORK="$(mktemp -d /tmp/nb_spa.XXXXXX)"
cleanup() { rm -rf "$WORK"; }
trap cleanup EXIT INT TERM

GEN="$WORK/mkdom"
cc -std=gnu11 -I"$PKG" -o "$GEN" "$HERE/g1_make_dom.c" "$PKG/nb_dom.c" 2>/dev/null \
    || { echo "FAIL: could not build the fixture generator"; exit 1; }
cat > "$WORK/page.html" <<'HTML'
<html><head><title>SPA</title></head><body>
<button id="btn">press me</button>
<p id="out">nothing yet</p>
<p>SPA: this paragraph must never change.</p>
</body></html>
HTML
"$GEN" "$WORK/page.html" "$WORK/page.dom" >/dev/null \
    || { echo "FAIL: fixture generator failed"; exit 1; }

cat > "$WORK/page.js" <<'JS'
// n is the page's own click counter. It is the observable that proves
// "no reload": a reload rebuilds the page, so n restarts at 0 and the next
// click reads "clicked 1" again. The suite's negative control forces a real
// reload to show exactly that - without it, "clicked 2" could just be a
// constant and the whole KPI would be vacuous.
var n = 0;
function onClick() {
    n = n + 1;
    var out = document.getElementById("out");
    if (out) { out.textContent = "clicked " + n; }
}
document.getElementById("btn").addEventListener("click", onClick);
JS

python3 - "$WORKER" "$WORK/page.js" "$WORK/page.dom" <<'PY'
import re, select, subprocess, sys, time

worker, js, dom = sys.argv[1], sys.argv[2], sys.argv[3]


def talk():
    p = subprocess.Popen([worker], stdin=subprocess.PIPE,
                         stdout=subprocess.PIPE, stderr=subprocess.DEVNULL,
                         bufsize=0)

    def send(payload):
        b = payload.encode()
        p.stdin.write(b"%06d\n" % len(b) + b + b"\n")
        p.stdin.flush()

    def read_frame(deadline):
        hdr = b""
        while len(hdr) < 7:
            left = deadline - time.time()
            if left <= 0:
                return None
            if not select.select([p.stdout], [], [], left)[0]:
                return None
            c = p.stdout.read(1)
            if not c:
                return None
            hdr += c
        n = int(hdr.decode().strip())
        body = b""
        while len(body) < n:
            left = deadline - time.time()
            if left <= 0:
                return None
            if not select.select([p.stdout], [], [], left)[0]:
                return None
            body += p.stdout.read(n - len(body))
        p.stdout.read(1)
        return body

    def command(payload, timeout=25):
        """Send one frame, collect everything up to STATUS."""
        send(payload)
        frames = []
        deadline = time.time() + timeout
        while time.time() < deadline:
            fr = read_frame(deadline)
            if fr is None:
                break
            frames.append(fr)
            if fr.startswith(b"STATUS"):
                break
        return frames
    return p, command


def texts(frames):
    out = []
    for f in frames:
        if f.startswith(b"RENDER\n"):
            out += [m.decode() for m in re.findall(rb"TEXT\|([^\n]*)", f)]
    return out


p, command = talk()
rc = 0

first = command("LOAD\n%s\n%s\nhttp://localhost/spa\nSPA\n\n" % (js, dom))
t0 = texts(first)
if not t0:
    print("FAIL: the page never rendered - the harness sees nothing")
    rc = 1

c1 = command("EVENT\n#btn\nclick\n")
t1 = texts(c1)
clicked = [t for t in t1 if t.startswith("clicked")]
print("  after LOAD:      %s" % [t for t in t0 if "nothing yet" in t or "press" in t])
print("  after click 1:   %s" % clicked)
print("  status:          %s" % [f.decode()[:40] for f in c1 if f.startswith(b"STATUS")])

if not clicked:
    print("FAIL: clicking #btn produced no re-render at all")
    rc = 1
elif "clicked 1" not in " ".join(clicked):
    print("FAIL: click did not re-render through the page's own handler: %s" % clicked)
    rc = 1
else:
    print("PASS: a click on a rendered row re-rendered without a reload")

# Second click: state must carry. A reload here would reset n AND loads.
c2 = command("EVENT\n#btn\nclick\n")
t2 = texts(c2)
clicked2 = [t for t in t2 if t.startswith("clicked")]
print("  after click 2:   %s" % clicked2)
if not clicked2:
    print("FAIL: the second click produced nothing - state did not survive")
    rc = 1
elif "clicked 2" not in " ".join(clicked2):
    if any("clicked 1" in t for t in clicked2):
        print("FAIL: the click RELOADED the page - n restarted at 1 instead of "
              "advancing to 2. This is the G1.5 regression, and it looks fine "
              "on screen.")
    else:
        print("FAIL: page state did not carry across clicks: %s" % clicked2)
    rc = 1
else:
    print("PASS: page state carried across clicks (n advanced 1 -> 2)")

# The invariant paragraph, and the absence of any navigation.
all_rows = " ".join(t1 + t2)
if "must never change" in all_rows:
    print("PASS: the invariant paragraph survived the clicks")
else:
    print("FAIL: the invariant paragraph vanished")
    rc = 1

if any(f.startswith(b"NAV|") for f in c1 + c2):
    print("FAIL: a click produced a NAV frame - that is a navigation, not a click")
    rc = 1
else:
    print("PASS: no navigation was triggered by the clicks")

# THE NEGATIVE TEST for the whole suite, and it exists because the first
# version of it was WRONG in an instructive way.
#
# I first counted loads with `window.__loads = (window.__loads||0)+1` and
# required it to read 2 after a genuine reload. It never did - and the
# negative test is what proved why: every LOAD builds a FRESH JS global, so
# that counter resets to 1 by construction and can never read 2. The "no
# reload" assertion had been reading a structural constant, i.e. it was
# vacuous, and nothing about the click path would ever have failed it.
#
# The control that actually has teeth uses the same observable the main
# assertion uses - n. A reload rebuilds the page, so n restarts at 0 and the
# next click reads "clicked 1". If the clicks above had reloaded, they
# would have read "clicked 1" too. They read "clicked 2", and a reload
# demonstrably resets that number.
reloaded = command("LOAD\n%s\n%s\nhttp://localhost/spa\nSPA\n\n" % (js, dom))
c3 = command("EVENT\n#btn\nclick\n")
after_reload = [t for t in texts(c3) if t.startswith("clicked")]
print("  LOAD then click:  %s" % after_reload)
if any("clicked 1" in t for t in after_reload):
    print("PASS: a real reload resets n to 0, so the 'clicked 2' above is "
          "evidence of NO reload rather than a constant")
else:
    print("FAIL: a real reload did not reset the page state, so the "
          "'no reload' assertions above are reading a constant and are void")
    rc = 1

p.kill()
sys.exit(rc)
PY
rc=$?
[ "$rc" -ne 0 ] && FAIL=1
[ "$FAIL" -eq 0 ] && echo "nb_spa_click_test.sh PASS"
exit $FAIL